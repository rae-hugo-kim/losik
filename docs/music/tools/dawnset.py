SET = [MORNING_GLASS, BLUE_HOUR, PAPER_KITE, LONG_BRIDGE]


def signatures():
    """§2-1/§2-2 유니크 검증: 진행 기능 시그니처(토닉 대비 interval, quality) + 훅 리듬·음정 시그니처."""
    out = {}
    for s in SET + [fl.FIRST_LIGHT]:
        key = s['key']
        pr = tuple(((PC[n] - key) % 12, q) for n, q in s['verse'] + s['chorus'])
        rhythm = tuple(tuple((b, d) for b, d, _ in bar) for bar in s['hook'])
        contour = tuple(tuple(p - s['hook'][0][0][2] for _, _, p in bar) for bar in s['hook'])
        out[s['sid']] = (pr, rhythm, contour)
    return out


if __name__ == '__main__':
    sig = signatures()
    vals = list(sig.values())
    assert len({v[0] for v in vals}) == len(vals), 'progression signature collision'
    assert len({(v[1], v[2]) for v in vals}) == len(vals), 'hook signature collision'
    only = sys.argv[1:]
    for s in SET:
        if only and s['sid'] not in only:
            continue
        msg, rng = fl.render(s)
        print(msg, '| lead', rng[fl.LD], 'top', rng[fl.HI])
