import firstlight as fl

NAMES = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'Ab', 'A', 'Bb', 'B']
ROMAN = {'I': (0, 'M'), 'ii': (2, 'm'), 'iii': (4, 'm'), 'IV': (5, 'M'), 'V': (7, 'M'), 'vi': (9, 'm')}
KEYSIG = {'C': 0, 'G': 1, 'D': 2, 'A': 3, 'E': 4, 'F': -1}


def prog(key, romans):
    return [(NAMES[(PC[key] + ROMAN[r][0]) % 12], ROMAN[r][1]) for r in romans.split()]


def lead_tonic(key):
    return fl.lead_tonic(PC[key])


def deg(key, d):
    return lead_tonic(key) + 12 * (d // 7) + fl.MAJOR[d % 7]


def bars(key, data):
    return [[(beat, dur, deg(key, d)) for beat, dur, d in bar] for bar in data]


def spec(sid, title, key, bpm, seed, verse, chorus, bridge, hook, top, verse_mel):
    return dict(
        sid=sid, title=title, bpm=bpm, keysig=KEYSIG[key], key=PC[key], seed=seed,
        verse=prog(key, verse), chorus=prog(key, chorus), bridge=prog(key, bridge), tail=prog(key, 'IV V I I'),
        hook=bars(key, hook), top=bars(key, top), verse_mel=bars(key, verse_mel),
    )


