"""Dawn Set (2026-09-08) — first-light 와 같은 형식(주제선율+드럼 도입 → 점층 → 탑노트 → 벌스/코러스 → 하이라이트 → 잔잔한 마무리)
으로 4곡. 편곡 엔진은 firstlight.compose, 곡별로 키·BPM·진행·주제선율·탑노트·벌스 멜로디를 전부 분리한다 (§2-1 클론 금지).

멜로디는 온음계 도수(0 = 으뜸음, 7 = 옥타브 위, 음수 = 아래)로 손으로 쓰고 키에 맞춰 절대 피치로 변환한다.
진행은 로마자 기능으로 쓰고 키에서 전개한다 — 4곡의 (벌스, 코러스) 기능 시그니처가 서로 다르다.

| sid            | 제목           | 키 / BPM | 벌스        | 코러스      | 훅 정체성 |
|----------------|----------------|----------|-------------|-------------|-----------|
| morning-glass  | Morning Glass  | G / 104  | I–vi–IV–V   | vi–IV–I–V   | '5–3–2–1' 하행 한숨 모티프, 마디 끝에서 되오름 |
| blue-hour      | Blue Hour      | E / 112  | I–iii–IV–V  | IV–I–V–vi   | 점8분 '1·1·↑' 옥타브 도약 모티프 |
| paper-kite     | Paper Kite     | A / 100  | I–IV–ii–V   | ii–IV–I–V   | 모든 마디가 반박 늦게 시작하는 당김 모티프 |
| long-bridge    | Long Bridge    | C / 116  | vi–IV–I–V   | I–V–ii–IV   | 5도 페달 반복(솔솔솔) 후 순차 이동 |
"""
import sys

